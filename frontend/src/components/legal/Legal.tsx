const CONSENT_KEY = 'automind-consent-v1'

/** Баннер согласия на обработку cookie (152-ФЗ). Показывается до первого согласия. */
export function ConsentBanner() {
  const [visible, setVisible] = useState(() => localStorage.getItem(CONSENT_KEY) !== 'accepted')
  const [doc, setDoc] = useState<LegalDoc>(null)
  if (!visible && !doc) return null
  return (
    <>
      {visible && (
        <div className="fixed inset-x-0 bottom-0 z-[1050] border-t border-automind-gray/30 bg-white px-6 py-3.5 shadow-[0_-2px_12px_rgba(23,28,25,0.12)]">
          <div className="mx-auto flex max-w-[1200px] flex-wrap items-center justify-between gap-3">
            <p className="max-w-[820px] text-[12px] leading-relaxed text-automind-ink">
              Сервис использует только необходимые cookie для поддержания сеанса работы. Продолжая работу,
              вы соглашаетесь с обработкой cookie в соответствии с{' '}
              <button onClick={() => setDoc('policy')} className="text-automind-dark underline">
                Политикой обработки персональных данных
              </button>{' '}
              и{' '}
              <button onClick={() => setDoc('agreement')} className="text-automind-dark underline">
                Пользовательским соглашением
              </button>
              .
            </p>
            <button
              onClick={() => {
                localStorage.setItem(CONSENT_KEY, 'accepted')
                setVisible(false)
              }}
              className="rounded-lg bg-automind-dark px-4 py-2 text-[13px] font-medium text-white"
            >
              Принять
            </button>
          </div>
        </div>
      )}
      {doc && <LegalModal doc={doc} onClose={() => setDoc(null)} />}
    </>
  )
}
