/** Модальное окно с юридическим документом. */
export function LegalModal({ doc, onClose }: { doc: Exclude<LegalDoc, null>; onClose: () => void }) {
  const title = doc === 'policy' ? 'Политика в отношении обработки персональных данных' : 'Пользовательское соглашение'
  const text = doc === 'policy' ? POLICY_TEXT.replace('${OPERATOR}', OPERATOR_PLACEHOLDER) : AGREEMENT_TEXT
  return (
    <div className="fixed inset-0 z-[1100] flex items-center justify-center bg-automind-ink/50 p-4">
      <div className="flex max-h-[85vh] w-full max-w-[720px] flex-col rounded-2xl bg-white shadow-lg">
        <div className="flex items-center justify-between border-b border-automind-gray/20 px-5 py-3.5">
          <h2 className="text-[15px] font-semibold">{title}</h2>
          <button onClick={onClose} className="text-automind-gray hover:text-automind-ink">
            ✕
          </button>
        </div>
        <div className="overflow-y-auto px-5 py-4">
          <p className="whitespace-pre-wrap text-[12.5px] leading-relaxed">{text}</p>
        </div>
        <div className="border-t border-automind-gray/20 px-5 py-3 text-right">
          <button onClick={onClose} className="rounded-lg bg-automind-dark px-4 py-2 text-[13px] font-medium text-white">
            Закрыть
          </button>
        </div>
      </div>
    </div>
  )
}

